"""Pick 一's best hits from the recorded matches and write remotion/src/moments.ts.

Each pick is recorded twice (pick_<stage>_<seed>.mp4 at normal speed and *_slow.mp4 at half speed).
Hits are matched between the two by their simulation time.
"""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FOOT = os.path.join(ROOT, 'footage')
LABEL = {
    'FrontKick': '前蹴り', 'GroundWave': '衝撃波', 'StrokeShot': '一画飛ばし', 'RecoverKick': '起き上がり蹴り',
    'PickupSlash': '拾い斬り', 'HookPull': '引き崩し', 'Thrust': '刺す', 'Sweep': '横薙ぎ', 'LowSweep': '足払い',
    'Bash': '盾当て', 'Launch': '打ち上げ', 'Spin': '回転斬り', 'Rising': '斬り上げ', 'Throw': '投げ', 'Smash': '叩き落とし',
    'Leap': '跳び斬り', 'DashSlash': '踏み込み斬り', 'Riposte': '受け流し反撃', 'Whirl': '全身ぶん回し', 'Overhead': '振り下ろし',
}


def read(path):
    hits, kos = [], []
    for line in open(path, encoding='utf-8'):
        f = line.rstrip('\n').split('\t')
        if len(f) < 2:
            continue
        if f[1] == 'hit' and len(f) >= 12:
            hits.append(dict(frame=int(f[0]), attacker=int(f[2]), damage=float(f[3]), style=f[4], crit=f[5] == 'crit',
                             down=f[6] == 'down', launch=f[7] == 'launch', combo=f[8] == 'combo', time=float(f[9]),
                             x=float(f[10]), y=float(f[11])))
        elif f[1] == 'ko' and len(f) >= 8:
            kos.append(dict(frame=int(f[0]), winner=int(f[2]), style=f[4], time=float(f[5]), x=float(f[6]), y=float(f[7])))
    return hits, kos


def main():
    moments = []
    for path in sorted(glob.glob(os.path.join(FOOT, 'pick_*.events.tsv'))):
        if path.endswith('_slow.events.tsv'):
            continue
        clip = os.path.basename(path)[:-len('.events.tsv')]
        slow = clip + '_slow'
        if not os.path.exists(os.path.join(FOOT, slow + '.events.tsv')):
            continue
        hits, kos = read(path)
        shits, skos = read(os.path.join(FOOT, slow + '.events.tsv'))
        ko_time = next((k['time'] for k in kos if k['winner'] == 0), None)
        for h in hits:
            if h['attacker'] != 0:
                continue
            match = [s for s in shits if s['attacker'] == 0 and abs(s['time'] - h['time']) < 1e-3 and s['style'] == h['style']]
            if not match:
                continue
            s = match[0]
            ko = ko_time is not None and abs(h['time'] - ko_time) < 1e-3
            score = h['damage'] + 12 * h['crit'] + 15 * h['down'] + 15 * h['launch'] + 20 * h['combo'] + 60 * ko
            moments.append(dict(clip=clip, slow=slow, hit=h['frame'], hitSlow=s['frame'], x=round(h['x']), y=round(h['y']),
                                style=h['style'], label=LABEL.get(h['style'], h['style']), damage=h['damage'],
                                critical=h['crit'], ko=ko, score=round(score, 1), time=h['time']))
    moments.sort(key=lambda m: -m['score'])
    for m in moments[:40]:
        print(f"{m['score']:6.1f} {m['clip']:28s} f{m['hit']:5d}/{m['hitSlow']:5d} {m['style']:10s} dmg {m['damage']:5.1f} "
              f"{'crit' if m['critical'] else ''} {'KO' if m['ko'] else ''} ({m['x']},{m['y']})")
    out = os.path.join(ROOT, 'remotion', 'src', 'moments.ts')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('import type {Moment} from \'./hit\';\n\n// Generated by PRVideo/tools/moments.py\n')
        f.write('export const MOMENTS: (Moment & {score: number; time: number})[] = ' + json.dumps(moments, ensure_ascii=False, indent=1) + ';\n')
    # Marks of the scripted clips (clicks, generation, special) for the edit.
    marks = {}
    for path in sorted(glob.glob(os.path.join(FOOT, '*.events.tsv'))):
        clip = os.path.basename(path)[:-len('.events.tsv')]
        if clip.startswith('pick_'):
            continue
        rows = []
        for line in open(path, encoding='utf-8'):
            f = line.rstrip('\n').split('\t')
            if len(f) >= 2 and f[1] != 'late':
                rows.append([int(f[0])] + f[1:])
        marks[clip] = rows
    with open(out, 'a', encoding='utf-8') as f:
        f.write('export const MARKS: Record<string, (string | number)[][]> = ' + json.dumps(marks, ensure_ascii=False) + ';\n')
    print('wrote', out, len(moments))


if __name__ == '__main__':
    main()
